// Runs after the client and SSR builds. Saves every page as finished HTML so search
// engines and AI crawlers (most don't run JavaScript) see the content, titles and
// structured data. Also writes sitemap.xml, _redirects and llms.txt from the same
// page list, so pages and programmes added through /admin are picked up on deploy.
import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../dist/public');
const entry = path.resolve(here, '../dist/server/entry-server.js');
const { render, PROGRAMMES, currentOnlineWorkshops, programmeUrlPath, SITE_URL, SITE_NAME } = await import(
  pathToFileURL(entry).href
);
const template = await readFile(path.join(out, 'index.html'), 'utf8');
if (!/<!--seo-->[\s\S]*<!--\/seo-->/.test(template) || !template.includes('<div id="root"></div>')) {
  throw new Error('index.html needs the <!--seo--> markers and an empty #root');
}

const STATIC_ROUTES = ['/', '/about', '/programmes', '/faq', '/testimonials', '/contact'];
const routes = [...new Set([...STATIC_ROUTES, ...PROGRAMMES.map(programmeUrlPath)])];
const fileFor = (r) => (r === '/' ? 'index.html' : `${r.slice(1)}.html`);
const today = new Date().toISOString().slice(0, 10);

// React 19 hoists <title>/<meta>/<link> from <Seo>; for a non-document render they
// come first in the output. Move them into <head>, marked so the browser can drop
// them before React adds its own.
function splitHead(html) {
  const m = html.match(/^(?:\s*(?:<title>[\s\S]*?<\/title>|<meta\b[^>]*>|<link\b[^>]*>))+/);
  const head = m ? m[0] : '';
  return { head: head.replace(/<(title|meta|link)\b/g, '<$1 data-prerendered=""'), body: html.slice(head.length) };
}

async function page(route, file) {
  const { head, body } = splitHead(await render(route));
  if (!head.includes('<title')) throw new Error(`${route}: no <title> from <Seo>`);
  if (/<script(?![^>]*application\/ld\+json)/.test(body)) throw new Error(`${route}: unexpected inline script`);
  const html = template.replace(/<!--seo-->[\s\S]*?<!--\/seo-->/, head).replace('<div id="root"></div>', `<div id="root">${body}</div>`);
  await mkdir(path.dirname(path.join(out, file)), { recursive: true });
  await writeFile(path.join(out, file), html);
  return { head, body };
}

const indexed = [];
for (const route of routes) {
  const { head } = await page(route, fileFor(route));
  if (/noindex/.test(head)) {
    console.warn(`skipped from sitemap (renders Not Found): ${route}`);
    continue;
  }
  indexed.push(route);
  console.log(`prerendered ${route}`);
}
await page('/this-page-does-not-exist', '404.html');
console.log('prerendered 404.html');

await writeFile(
  path.join(out, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${indexed
    .map((r) => `  <url><loc>${SITE_URL}${r === '/' ? '/' : r}</loc><lastmod>${today}</lastmod></url>`)
    .join('\n')}\n</urlset>\n`,
);

// _redirects is read before netlify.toml rules, so the admin rules live here too,
// ahead of the catch-all 404.
await writeFile(
  path.join(out, '_redirects'),
  [
    '# Generated by scripts/prerender.mjs',
    '/admin                       /admin/index.html                 200',
    '/admin/*                     /admin/index.html                 200',
    '/programmes/revert-classes   /programmes/in-person-workshops   301',
    ...indexed.filter((r) => r !== '/').map((r) => `${r}  ${r}.html  200`),
    '/*                           /404.html                         404',
    '',
  ].join('\n'),
);

const upcoming = currentOnlineWorkshops(new Date());
await writeFile(
  path.join(out, 'llms.txt'),
  `# ${SITE_NAME}

> A beginner-friendly Islamic learning space for women and children in Cape Town, South Africa, founded by Mualimah Rukeya in 2024. Online classes (Google Classroom, Microsoft Teams) and in-person classes in Mitchell's Plain, Cape Town.

Enrolment enquiries: WhatsApp +27 68 649 8593. Instagram: https://instagram.com/beginners_classes

## Programmes
${PROGRAMMES.map((p) => `- [${p.title}](${SITE_URL}${programmeUrlPath(p)}): ${p.descLong} ${p.tag}. ${p.price}.`).join('\n')}
${
  upcoming.length
    ? `\n## Upcoming workshops\n${upcoming
        .map((w) => `- ${w.title}: ${w.description}${(w.details ?? []).map((d) => ` ${d.label}: ${d.value}.`).join('')}`)
        .join('\n')}\n`
    : ''
}
## Pages
- [Home](${SITE_URL}/)
- [Our Story](${SITE_URL}/about): about Mualimah Rukeya and how the madrasah started
- [Programmes](${SITE_URL}/programmes): all programmes and prices
- [FAQ](${SITE_URL}/faq): getting started, platforms, payments
- [Testimonials](${SITE_URL}/testimonials)
- [Contact](${SITE_URL}/contact)

Generated ${today} from the site's content.
`,
);
console.log(`sitemap.xml (${indexed.length} pages), _redirects, llms.txt`);

await rm(path.resolve(here, '../dist/server'), { recursive: true, force: true });
